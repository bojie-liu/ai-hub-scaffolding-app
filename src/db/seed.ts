// --- Seed versions ---
const V1_SEED_VERSION = 'v1_initial';
const V2_SEED_VERSION = 'v2_lesson_data';

// --- Ensure _seed_log table exists ---
async function ensureSeedLogTable(db: ReturnType<typeof drizzle>) {
  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS _seed_log (
      id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      seed_version text NOT NULL UNIQUE,
      applied_at timestamp DEFAULT now()
    )
  `);
}

// --- Check if a seed version has already been applied ---
async function isSeedApplied(
  db: ReturnType<typeof drizzle>,
  version: string,
): Promise<boolean> {
  const existing = await db
    .select()
    .from(schema.seedLog)
    .where(eq(schema.seedLog.seedVersion, version))
    .limit(1);
  return existing.length > 0;
}

// --- v1_initial: Create admin user ---
async function seedV1(db: ReturnType<typeof drizzle>) {
  if (await isSeedApplied(db, V1_SEED_VERSION)) {
    console.log(`Seed "${V1_SEED_VERSION}" already applied. Skipping.`);
    return;
  }

  await db.transaction(async (tx) => {
    const passwordHash = await bcrypt.hash(
      process.env.SEED_ADMIN_PASSWORD || 'changeme',
      10,
    );

    await tx.insert(schema.users).values({
      username: 'admin',
      email: 'admin@example.com',
      passwordHash,
      role: 'TEACHER',
      displayName: 'Admin User',
    });

    await tx.insert(schema.seedLog).values({
      seedVersion: V1_SEED_VERSION,
    });
  });

  console.log(`Seed "${V1_SEED_VERSION}" applied successfully.`);
}

